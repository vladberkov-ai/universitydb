"""Capture only known offline pytest M1 proofs and their verified matching JSONLs.

Does not run the application, open databases, read environment/credentials/ledger,
perform network requests or modify runtime/native/Git state. Run only after the
specified pytest run actually passed; --verification records that observed result.
"""

import argparse
import hashlib
import json
import shutil
from pathlib import Path


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pytest_root", type=Path)
    parser.add_argument("--verification", required=True)
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[4]
    output = args.output_dir or Path(__file__).resolve().parent
    if args.output_dir is not None:
        if output.exists():
            raise ValueError(
                "Output directory exists; preserve earlier proof and choose a new path."
            )
        output.mkdir(parents=True)
    elif (output / "manifest.json").exists():
        raise ValueError("Existing evidence is preserved; specify a new --output-dir.")
    names = [
        "agent.py",
        "contracts.py",
        "db.py",
        "db_worker.py",
        "sql_policy.py",
        "config.py",
        "llm.py",
        "llm_worker.py",
        "tracing.py",
        "prompts/plan.txt",
        "prompts/sql.txt",
        "domain.py",
        "domain_support.py",
        "library.py",
    ]
    paths = [Path("src/universitydb") / name for name in names] + [
        Path("tests/test_i3_dependencies.py"),
        Path("docs/operations/H-013/frozen-oracle.json"),
    ]
    hashes = {str(path): sha(root / path) for path in paths}
    manifest = {
        "evidence": args.verification,
        "profile": "offline/injected; not real-model NL-to-SQL accuracy",
        "source_sha256": hashes,
        "cases": {},
    }
    for case in ("F1", "F2", "tie"):
        sources = {
            path.resolve()
            for path in args.pytest_root.glob(
                "test_m1_actual_dependency_sens*/m1-proof-" + case + ".json"
            )
        }
        if len(sources) != 1:
            raise ValueError("Expected exactly one known M1 proof per case.")
        source = sources.pop()
        proof = json.loads(source.read_text())
        if proof["case"] != case or proof["profile"] != manifest["profile"]:
            raise ValueError("Case or offline provenance differs.")
        # Source proof's basename is generated by the UUID application run, not a client path.
        basename = proof["trace_basename"]
        if Path(basename).name != basename or not basename.endswith(".jsonl"):
            raise ValueError("Invalid trace basename.")
        trace = source.parent / "traces" / basename
        if sha(trace) != proof["trace_sha256"]:
            raise ValueError("Trace identity does not match actual proof.")
        proof["source_sha256"] = hashes
        proof["trace_basename"] = case + ".jsonl"
        (output / (case + ".json")).write_text(json.dumps(proof, indent=2) + "\n")
        shutil.copyfile(trace, output / (case + ".jsonl"))
        manifest["cases"][case] = {
            "proof": case + ".json",
            "trace": case + ".jsonl",
            "trace_sha256": proof["trace_sha256"],
            "expected_top": proof["expected"]["top_course_ids"],
            "actual_top": proof["steps"][0]["dependency_rows"],
            "actual_final": proof["actual_answer"]["rows"],
            "provider_calls": len(proof["provider_history"]),
        }
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")


if __name__ == "__main__":
    main()
