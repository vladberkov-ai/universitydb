def test_active_budget_rechecked_after_preparation_before_provider_dispatch(tmp_path):
    provider = ScriptedProvider([])
    agent = Agent(University(), tmp_path / "unused.sqlite", provider, tmp_path / "trace")
    agent.trace = Trace(tmp_path / "trace", "deadline")
    agent.deadline = float("inf")
    emit = agent.trace.emit

    def preparation_consumes_remainder(node, kind, payload, attempt=0):
        emit(node, kind, payload, attempt)
        if kind == "llm_attempt":
            agent.deadline = 0

    with (
        patch.object(agent.trace, "emit", preparation_consumes_remainder),
        pytest.raises(Failure) as error,
    ):
        agent._call("plan", {"question": "mean all", "descriptor": {}, "scope": {}}, PlanProposal)
    assert error.value.code == "BUDGET_EXCEEDED"
    assert provider.calls == 0


def test_retained_result_copies_share_one_128k_run_ceiling(tmp_path):
    """Fault-injected valid SQLite typed strings fit64KiB, retained copies do not."""
    from universitydb.library import SPEC, Library

    database = tmp_path / "library.sqlite"
    db.initialize(database, Path("resources/library"))
    domain = Library()
    sql, params = domain.query(SPEC, {})
    plan, first = scripted_step(SPEC, sql, params, "one")
    second = deepcopy(plan["steps"][0])
    second["step_id"] = "two"
    plan["steps"].append(second)
    second_sql = scripted_step(SPEC, sql, params, "two")[1]
    provider = ScriptedProvider([plan, first, second_sql])
    agent = Agent(domain, database, provider, tmp_path / "retained")
    original = agent._action
    raw_bytes = bundle_bytes = 0

    def large_rows(name, state):
        nonlocal raw_bytes, bundle_bytes
        update = original(name, state)
        if name == "execute" and state["step_index"] == 0:
            raw = {
                **update["result"],
                "rows": [[i, "N" * 500, 1] for i in range(1, 101)],
                "row_count": 100,
            }
            adapted = domain.adapt_result(raw["rows"], SPEC, state["scope"])
            outcome = {"step_id": "one", "raw": raw, **adapted}
            bundle = {
                "result": raw,
                "completed": {"one": raw},
                "step_results": [outcome],
                "answer": adapted["answer"],
            }
            raw_bytes = len(json.dumps(raw, ensure_ascii=False).encode())
            bundle_bytes = len(json.dumps(bundle, ensure_ascii=False).encode())
            update["result"] = raw
        return update

    with patch.object(agent, "_action", large_rows):
        result = agent.run("open loans per reader")
    assert raw_bytes < 65536
    assert bundle_bytes > 131072
    assert result["error"]["code"] == "RESOURCE_LIMIT"
    assert result["error"]["failed_node"] == "inspect_result"
    assert result["answer"] is None and provider.calls == 2
    assert len([e for e in result["events"] if e["kind"] == "sql_attempt"]) == 1
    assert not result["step_results"]
