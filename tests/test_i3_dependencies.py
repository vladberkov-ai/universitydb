@pytest.mark.parametrize(
    "corruption", ["missing", "type", "spec", "truncated", "oversized", "count"]
)
def test_invalid_actual_upstream_stops_before_any_downstream_dispatch(
    database, tmp_path, corruption
):
    provider = ActualReferenceProvider()
    agent = Agent(University(), database, provider, tmp_path / "traces")
    original = agent._action

    def corrupt(name, state):
        update = original(name, state)
        if name == "inspect_result" and state["step_index"] == 0:
            completed = deepcopy(update["completed"])
            raw = completed["top"]
            if corruption == "missing":
                completed = {}
            elif corruption == "type":
                raw["rows"][0][0] = "2"
            elif corruption == "spec":
                raw["result_spec"]["unit"] = "invented"
            elif corruption == "truncated":
                raw["truncated"] = True
            elif corruption == "oversized":
                raw["rows"] *= 101
                raw["row_count"] = len(raw["rows"])
            else:
                raw["row_count"] = 0
            update["completed"] = completed
        return update

    with patch.object(agent, "_action", corrupt):
        result = agent.run(QUESTION)
    assert result["error"]["code"] == (
        "RESULT_TOO_LARGE" if corruption in ("truncated", "oversized") else "DEPENDENCY_INVALID"
    ), result
    assert result["error"]["failed_node"] == "bind_results"
    assert provider.calls == 2 and len(provider.proposals) == 1
    assert result["answer"] is None
    assert len([e for e in result["events"] if e["kind"] == "sql_attempt"]) == 1


def test_injected_empty_cohort_never_loses_filter(database, tmp_path):
    """Explicit valid-shape empty intermediate injection, not a natural top-course fixture."""
    provider = ActualReferenceProvider()
    agent = Agent(University(), database, provider, tmp_path / "traces")
    original = agent._action

    def empty(name, state):
        update = original(name, state)
        if name == "execute" and state["step_index"] == 1:
            update["result"].update(rows=[], row_count=0)
        return update

    with patch.object(agent, "_action", empty):
        result = agent.run(QUESTION)
    assert result["status"] == "ok"
    assert result["answer"]["rows"] == [] and result["answer"]["empty_reason"] == "no_rows"
    assert provider.calls == 3
    assert not any(proposal["step_id"] == "means" for proposal in provider.proposals)


