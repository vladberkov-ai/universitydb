QUESTION = "For students of the top course in S1 show their mean across all S1 courses"
ORACLE = json.loads(Path("docs/operations/H-013/frozen-oracle.json").read_text())["m1"]


def dependency_plan():
    steps = []
    for step_id, spec, upstream, column, bind_as in (
        ("top", make_spec("top_course", "course_id"), None, None, None),
        ("cohort", make_spec("student_ids"), "top", "course_id", "course_ids"),
        ("means", make_spec("grade_mean", "student_id"), "cohort", "student_id", "student_ids"),
    ):
        steps.append(
            {
                "step_id": step_id,
                "purpose": step_id,
                "result_spec": spec.model_dump(),
                "depends_on": [upstream] if upstream else [],
                "result_refs": [
                    {"from_step": upstream, "column": column, "type": "integer", "bind_as": bind_as}
                ]
                if upstream
                else [],
            }
        )
    return {
        "version": "1",
        "steps": steps,
        "needs_clarification": False,
        "clarification_field": None,
    }


class ActualReferenceProvider(ScriptedProvider):
    """Injected offline SQL transport: query values come only from received actual refs."""

    def __init__(self, *, transient_first=False, fail_step=None):
        super().__init__([])
        self.plan = dependency_plan()
        self.history: list[dict[str, Any]] = []
        self.proposals: list[dict[str, Any]] = []
        self.transient_first = transient_first
        self.fail_step = fail_step
        self.fixture_hash = hashlib.sha256(
            json.dumps(self.plan, sort_keys=True).encode()
        ).hexdigest()

    def call(self, operation, payload, output_type, *, timeout=180):
        self.calls += 1
        self.history.append({"operation": operation, "payload": deepcopy(payload)})
        if self.transient_first and self.calls == 1:
            raise Failure("PROVIDER_TRANSIENT", "Injected one transport failure.")
        if operation == "plan":
            value = self.plan
        else:
            step = payload["step"]
            if step["step_id"] == self.fail_step:
                raise Failure("PROVIDER_REFUSAL", "Injected terminal failure after prior success.")
            # This is the crucial portability boundary: no fixture name/index supplies bound IDs.
            spec = (
                PlanProposal.model_validate(self.plan)
                .steps[[s["step_id"] for s in self.plan["steps"]].index(step["step_id"])]
                .result_spec
            )
            sql, params = University().query(spec, payload["scope"], payload["resolved_refs"])
            value = scripted_step(spec, sql, params, step["step_id"])[1]
            self.proposals.append(deepcopy(value))
        return output_type.model_validate(value), {
            "input_tokens": 0,
            "output_tokens": 0,
            "total_tokens": 0,
            "real_provider_called": False,
            "fixture_sha256": self.fixture_hash,
            "injection_point": "dynamic_actual_reference_transport",
        }


def run_case(database, tmp_path, case="F1", provider=None):
    with sqlite3.connect(database) as connection:
        connection.execute("DELETE FROM Enrollments")
        connection.executemany("INSERT INTO Enrollments VALUES(?,?,?)", ORACLE[case]["enrollments"])
    provider = provider or ActualReferenceProvider()
    agent = Agent(University(), database, provider, tmp_path / "traces")
    before = db.file_hash(database)
    result = agent.run(QUESTION, request_id="m1-start")
    assert db.file_hash(database) == before
    return agent, provider, result


@pytest.mark.parametrize("case", ["F1", "F2", "tie"])
def test_m1_actual_dependency_sensitivity(database, tmp_path, case):
    agent, provider, result = run_case(database, tmp_path, case)
    expected = ORACLE[case]
    assert result["status"] == "ok", result
    assert provider.calls == 4
    payloads = [entry["payload"] for entry in provider.history if entry["operation"] == "sql"]
    assert payloads[0]["resolved_refs"] == {}
    assert payloads[1]["resolved_refs"] == {"course_ids": expected["top_course_ids"]}
    assert payloads[2]["resolved_refs"] == {"student_ids": expected["cohort_student_ids"]}
    assert result["answer"]["rows"] == [
        [row["key"], row["mean"], row["raw"][1], row["raw"][2]] for row in expected["final"]
    ]
    assert result["answer"]["row_reasons"] == [row["reason"] for row in expected["final"]]
    assert [row[0] for row in result["step_results"][0]["dependency_rows"]] == expected[
        "top_course_ids"
    ]
    assert [row[0] for row in result["step_results"][1]["dependency_rows"]] == expected[
        "cohort_student_ids"
    ]
    proposals = provider.proposals
    assert [
        binding["integer_value"]
        for binding in proposals[1]["parameters"]
        if binding["name"].startswith("course_ids_")
    ] == expected["top_course_ids"]
    assert [
        binding["integer_value"]
        for binding in proposals[2]["parameters"]
        if binding["name"].startswith("student_ids_")
    ] == expected["cohort_student_ids"]
    assert ":course_ids_0" in proposals[1]["sql"]
    assert ":student_ids_0" in proposals[2]["sql"]
    assert agent.run(QUESTION, request_id="m1-start") == result
    assert provider.calls == 4
    proof = {
        "case": case,
        "expected": expected,
        "actual_answer": result["answer"],
        "steps": result["step_results"],
        "provider_history": provider.history,
        "sql_proposals": provider.proposals,
        "run_id": result["run_id"],
        "trace_basename": result["run_id"] + ".jsonl",
        "trace_sha256": db.file_hash(tmp_path / "traces" / (result["run_id"] + ".jsonl")),
        "profile": "offline/injected; not real-model NL-to-SQL accuracy",
    }
    (tmp_path / ("m1-proof-" + case + ".json")).write_text(json.dumps(proof, indent=2))


